export type RailVariant = "hero" | "preview" | "sweep" | "connect";

export function railPaths(variant: RailVariant, width: number, height: number) {
  const x = (value: number) => Number(((value * width) / 1600).toFixed(2));
  const y = (value: number) => Number(((value * height) / 720).toFixed(2));
  const p = (a: number, b: number) => `${x(a)} ${y(b)}`;
  if (variant === "preview")
    return [
      `M${p(-80, 90)}H${x(250)}C${p(370, 90)} ${p(410, 245)} ${p(535, 245)}C${p(630, 245)} ${p(665, 90)} ${p(800, 90)}C${p(935, 90)} ${p(970, 245)} ${p(1065, 245)}C${p(1190, 245)} ${p(1230, 90)} ${p(1350, 90)}H${x(1680)}`,
      `M${p(1680, 315)}H${x(1305)}C${p(1165, 315)} ${p(1140, 420)} ${p(1000, 420)}H${x(600)}C${p(460, 420)} ${p(435, 315)} ${p(295, 315)}H${x(-80)}`,
    ];
  if (variant === "sweep")
    return [
      `M${p(-100, 20)}H${x(750)}Q${p(805, 20)} ${p(838, 75)}L${p(960, 285)}Q${p(995, 340)} ${p(1050, 340)}H${x(1700)}`,
      `M${p(-100, 108)}H${x(1070)}Q${p(1125, 108)} ${p(1158, 163)}L${p(1278, 370)}Q${p(1310, 425)} ${p(1370, 425)}H${x(1700)}`,
    ];
  if (variant === "connect")
    return [
      `M${p(-50, 25)}H${x(135)}Q${p(190, 25)} ${p(225, 80)}L${p(365, 307)}Q${p(397, 360)} ${p(455, 360)}H${x(1145)}Q${p(1203, 360)} ${p(1235, 307)}L${p(1375, 80)}Q${p(1410, 25)} ${p(1465, 25)}H${x(1650)}`,
      `M${p(-50, 695)}H${x(135)}Q${p(190, 695)} ${p(225, 640)}L${p(365, 413)}Q${p(397, 360)} ${p(455, 360)}H${x(1145)}Q${p(1203, 360)} ${p(1235, 413)}L${p(1375, 640)}Q${p(1410, 695)} ${p(1465, 695)}H${x(1650)}`,
    ];
  return [
    `M${p(-80, 85)}H${x(155)}Q${p(210, 85)} ${p(244, 144)}L${p(418, 445)}Q${p(453, 505)} ${p(515, 505)}H${x(1100)}Q${p(1162, 505)} ${p(1198, 445)}L${p(1372, 144)}Q${p(1407, 85)} ${p(1462, 85)}H${x(1680)}`,
    `M${p(-80, 200)}H${x(335)}Q${p(388, 200)} ${p(421, 259)}L${p(554, 491)}Q${p(589, 552)} ${p(650, 552)}H${x(947)}Q${p(1008, 552)} ${p(1042, 491)}L${p(1175, 259)}Q${p(1208, 200)} ${p(1260, 200)}H${x(1680)}`,
  ];
}
